(
    id_ponto INTEGER NOT NULL,
    nm_endereco VARCHAR2(50) NOT NULL,
    nr_endereco INTEGER NOT NULL,
    CONSTRAINT T_CT_PONTO_ONIBUS_PK PRIMARY KEY (id_ponto)
);

CREATE TABLE T_CT_ONIBUS
(
    id_onibus INTEGER NOT NULL,
    nr_placa VARCHAR2(10) NOT NULL,
    st_onibus VARCHAR2(20) NOT NULL,
    CONSTRAINT T_CT_ONIBUS_PK PRIMARY KEY (id_onibus),
    CONSTRAINT T_CT_ONIBUS_UK UNIQUE (nr_placa),
    CONSTRAINT T_CT_ONIBUS_STATUS_CK
        CHECK (st_onibus IN (
            'MANUTENCAO',
            'DISPONIVEL',
            'INDISPONIVEL'
        ))
);

CREATE TABLE T_CT_LINHA_PONTO
(
    id_linha_ponto INTEGER NOT NULL,
    nr_sequencia INTEGER NOT NULL,
    T_CT_LINHA_id_linha INTEGER NOT NULL,
    T_CT_PONTO_ONIBUS_id_ponto INTEGER NOT NULL,
    CONSTRAINT T_CT_LINHA_PONTO_PK PRIMARY KEY (id_linha_ponto),
    CONSTRAINT T_CT_LINHA_PONTO_LINHA_PONTO_UK
        UNIQUE (
            T_CT_LINHA_id_linha,
            T_CT_PONTO_ONIBUS_id_ponto
        ),
    CONSTRAINT T_CT_LINHA_PONTO_SEQUENCIA_UK
        UNIQUE (
            T_CT_LINHA_id_linha,
            nr_sequencia
        ),
    CONSTRAINT T_CT_LINHA_PONTO_SEQUENCIA_CK
        CHECK (nr_sequencia > 0),
    CONSTRAINT T_CT_LINHA_PONTO_LINHA_FK
        FOREIGN KEY (T_CT_LINHA_id_linha)
        REFERENCES T_CT_LINHA (id_linha),
    CONSTRAINT T_CT_LINHA_PONTO_PONTO_FK
        FOREIGN KEY (T_CT_PONTO_ONIBUS_id_ponto)
        REFERENCES T_CT_PONTO_ONIBUS (id_ponto)
);

CREATE TABLE T_CT_OPERACAO
(
    id_operacao INTEGER NOT NULL,
    dt_operacao DATE NOT NULL,
    hr_inicio NUMBER(4) NOT NULL,
    hr_fim NUMBER(4) NOT NULL,
    T_CT_LINHA_id_linha INTEGER NOT NULL,
    T_CT_ONIBUS_id_onibus INTEGER NOT NULL,
    CONSTRAINT T_CT_OPERACAO_PK PRIMARY KEY (id_operacao),
    CONSTRAINT T_CT_OPERACAO_DATA_CK
        CHECK (dt_operacao = TRUNC(dt_operacao)),
    CONSTRAINT T_CT_OPERACAO_INICIO_CK
        CHECK (hr_inicio BETWEEN 0 AND 1439),
    CONSTRAINT T_CT_OPERACAO_FIM_CK
        CHECK (hr_fim BETWEEN 1 AND 1440),
    CONSTRAINT T_CT_OPERACAO_HORARIO_CK
        CHECK (hr_fim > hr_inicio),
    CONSTRAINT T_CT_OPERACAO_LINHA_FK
        FOREIGN KEY (T_CT_LINHA_id_linha)
        REFERENCES T_CT_LINHA (id_linha),
    CONSTRAINT T_CT_OPERACAO_ONIBUS_FK
        FOREIGN KEY (T_CT_ONIBUS_id_onibus)
        REFERENCES T_CT_ONIBUS (id_onibus)
);

CREATE TABLE T_CT_REGSITRO
(
    id_registro INTEGER NOT NULL,
    dt_chegada DATE NOT NULL,
    T_CT_PONTO_ONIBUS_id_ponto INTEGER NOT NULL,
    T_CT_OPERACAO_id_operacao INTEGER NOT NULL,
    CONSTRAINT T_CT_REGSITRO_PK PRIMARY KEY (id_registro),
    CONSTRAINT T_CT_REGSITRO_PONTO_FK
        FOREIGN KEY (T_CT_PONTO_ONIBUS_id_ponto)
        REFERENCES T_CT_PONTO_ONIBUS (id_ponto),
    CONSTRAINT T_CT_REGSITRO_OPERACAO_FK
        FOREIGN KEY (T_CT_OPERACAO_id_operacao)
        REFERENCES T_CT_OPERACAO (id_operacao)
);

CREATE OR REPLACE TRIGGER TR_CT_OPERACAO_CONFLITO
FOR INSERT OR UPDATE ON T_CT_OPERACAO
COMPOUND TRIGGER

    TYPE T_IDS IS TABLE OF T_CT_OPERACAO.id_operacao%TYPE
        INDEX BY PLS_INTEGER;

    V_IDS T_IDS;
    V_CONTADOR PLS_INTEGER := 0;

    BEFORE STATEMENT IS
    BEGIN
        V_CONTADOR := 0;
    END BEFORE STATEMENT;

    AFTER EACH ROW IS
    BEGIN
        V_CONTADOR := V_CONTADOR + 1;
        V_IDS(V_CONTADOR) := :NEW.id_operacao;
    END AFTER EACH ROW;

    AFTER STATEMENT IS
        V_ONIBUS INTEGER;
        V_DATA DATE;
        V_INICIO NUMBER;
        V_FIM NUMBER;
        V_CONFLITOS INTEGER;
    BEGIN
        FOR I IN 1 .. V_CONTADOR LOOP

            SELECT
                T_CT_ONIBUS_id_onibus,
                dt_operacao,
                hr_inicio,
                hr_fim
            INTO
                V_ONIBUS,
                V_DATA,
                V_INICIO,
                V_FIM
            FROM T_CT_OPERACAO
            WHERE id_operacao = V_IDS(I);

            SELECT COUNT(*)
            INTO V_CONFLITOS
            FROM T_CT_OPERACAO
            WHERE T_CT_ONIBUS_id_onibus = V_ONIBUS
              AND dt_operacao = V_DATA
              AND id_operacao <> V_IDS(I)
              AND hr_inicio < V_FIM
              AND hr_fim > V_INICIO;

            IF V_CONFLITOS > 0 THEN
                RAISE_APPLICATION_ERROR(
                    -20001,
                    'O onibus ja possui outra operacao nesse horario.'
                );
            END IF;

        END LOOP;
    END AFTER STATEMENT;

END TR_CT_OPERACAO_CONFLITO;
/

CREATE OR REPLACE TRIGGER TR_CT_REGSITRO_PONTO
BEFORE INSERT OR UPDATE ON T_CT_REGSITRO
FOR EACH ROW
DECLARE
    V_LINHA INTEGER;
    V_EXISTE INTEGER;
BEGIN
    SELECT T_CT_LINHA_id_linha
    INTO V_LINHA
    FROM T_CT_OPERACAO
    WHERE id_operacao = :NEW.T_CT_OPERACAO_id_operacao;

    SELECT COUNT(*)
    INTO V_EXISTE
    FROM T_CT_LINHA_PONTO
    WHERE T_CT_LINHA_id_linha = V_LINHA
      AND T_CT_PONTO_ONIBUS_id_ponto =
          :NEW.T_CT_PONTO_ONIBUS_id_ponto;

    IF V_EXISTE = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20002,
            'O ponto informado nao pertence a linha da operacao.'
        );
    END IF;
END;
